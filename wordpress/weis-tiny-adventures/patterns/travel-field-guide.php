<h3 class="wp-block-heading wei-topic-title">On the road</h3>
<!-- /wp:heading -->

<!-- wp:details {"showContent":true,"className":"tips-note"} -->
<details class="wp-block-details tips-note" open><summary>Learn the little words that open doors.</summary>
<!-- wp:group {"className":"tips-note-copy"} -->
<div class="wp-block-group tips-note-copy">
<!-- wp:paragraph -->
<p>A hello, please, and thank you in the local language go a long way. Save a few phrases offline, follow local etiquette, and ask before taking someone’s photo.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"tips-takeaway"} -->
<p class="tips-takeaway">A little curiosity makes a place feel less unfamiliar.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"tips-note"} -->
<details class="wp-block-details tips-note"><summary>Leave room for a slower morning.</summary>
<!-- wp:group {"className":"tips-note-copy"} -->
<div class="wp-block-group tips-note-copy">
<!-- wp:paragraph -->
<p>You don’t have to fill every hour. Give yourself time to walk down an interesting street, linger over breakfast, or head back early when you need a rest. Your itinerary can be an invitation rather than a checklist.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"tips-takeaway"} -->
<p class="tips-takeaway">An unplanned hour is still part of the adventure.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

