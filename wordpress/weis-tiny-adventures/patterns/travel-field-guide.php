<h3 class="wp-block-heading wei-topic-title">Before you go</h3>
<!-- /wp:heading -->

<!-- wp:details {"showContent":true,"className":"tips-note"} -->
<details class="wp-block-details tips-note" open><summary>Plan the first night. Leave a little space after that.</summary>
<!-- wp:group {"className":"tips-note-copy"} -->
<div class="wp-block-group tips-note-copy">
<!-- wp:paragraph -->
<p>Save your accommodation address, check how you’ll get there from the airport or station, and note the check-in time. With the arrival sorted, you can leave a few afternoons open for something you stumble across.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"tips-takeaway"} -->
<p class="tips-takeaway">A settled first night is a lovely way to start.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"tips-note"} -->
<details class="wp-block-details tips-note"><summary>Keep the useful things available offline.</summary>
<!-- wp:group {"className":"tips-note-copy"} -->
<div class="wp-block-group tips-note-copy">
<!-- wp:paragraph -->
<p>Download the maps you’ll need and save booking confirmations, transport details, and important contacts somewhere you can reach without mobile data. Keep personal documents protected on your device.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"tips-takeaway"} -->
<p class="tips-takeaway">Try opening your essentials in flight mode before you leave.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"tips-note"} -->
<details class="wp-block-details tips-note"><summary>Check the details before you hit “book”.</summary>
<!-- wp:group {"className":"tips-note-copy"} -->
<div class="wp-block-group tips-note-copy">
<!-- wp:paragraph -->
<p>Read the current official advice for your destination, then check entry requirements with the relevant government and your airline. Look at the cancellation terms and what your travel insurance actually covers for your plans.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"tips-takeaway"} -->
<p class="tips-takeaway">Use the country safety check above as your starting point.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
