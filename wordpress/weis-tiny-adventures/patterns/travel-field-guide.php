<!-- wp:heading {"level":3,"className":"wei-topic-title"} -->
<h3 class="wp-block-heading wei-topic-title">Spend less</h3>
<!-- /wp:heading -->

<!-- wp:details {"showContent":true,"className":"tips-note"} -->
<details class="wp-block-details tips-note" open><summary>Compare the whole journey, not just the ticket.</summary>
<!-- wp:group {"className":"tips-note-copy"} -->
<div class="wp-block-group tips-note-copy">
<!-- wp:paragraph -->
<p>A cheaper flight can come with baggage charges, a distant airport, or an overnight stop. Add up the fare, transfers, bags, and any extra accommodation before you choose. Flexing your dates can open up more options too.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"tips-takeaway"} -->
<p class="tips-takeaway">The total cost tells a more useful story than the headline fare.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"tips-note"} -->
<details class="wp-block-details tips-note"><summary>Pick a base you can explore on foot.</summary>
<!-- wp:group {"className":"tips-note-copy"} -->
<div class="wp-block-group tips-note-copy">
<!-- wp:paragraph -->
<p>Put the places you’re excited about on a map before booking your stay. Somewhere walkable or close to public transport may leave more of your budget for the trip itself, even if the nightly rate is a little higher.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"tips-takeaway"} -->
<p class="tips-takeaway">Compare the room price and the cost of getting around together.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"tips-note"} -->
<details class="wp-block-details tips-note"><summary>Give your day one thing to look forward to.</summary>
<!-- wp:group {"className":"tips-note-copy"} -->
<div class="wp-block-group tips-note-copy">
<!-- wp:paragraph -->
<p>Choose the meal, experience, or outing you really care about, then build a slower day around it. Local markets, neighbourhood walks, public gardens, and a picnic can be just as memorable as a packed list of paid attractions.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"tips-takeaway"} -->
<p class="tips-takeaway">Keep a little room in the budget for a happy discovery.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:paragraph {"className":"tips-notebook-signoff"} -->
<p class="tips-notebook-signoff">Spend on the moments you’ll remember.</p>
<!-- /wp:paragraph -->

